package com.zhuqiyun.platform;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.zaxxer.hikari.HikariDataSource;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import java.sql.Timestamp;
import java.time.Instant;
import java.time.LocalDateTime;
import java.util.Map;
import java.util.TimeZone;
import static org.junit.jupiter.api.Assertions.*;

/** Regression: the same instant must survive JVM timezone changes and retain its explicit UTC offset. */
class PlatformTimeTest {
    @Test void utcOptionsOverrideLegacyAndConflictingUrlOptionsWithoutChangingOtherOptions() {
        String url=JdbcTimeConfig.utcUrl("jdbc:mysql://localhost/db?permitMysqlScheme=true&serverTimezone=Asia/Shanghai&connectionTimeZone=LOCAL&preserveInstants=false&timezone=Asia/Tokyo&forceConnectionTimeZoneToSession=false&useSSL=false");
        assertEquals("jdbc:mysql://localhost/db?permitMysqlScheme=true&useSSL=false&connectionTimeZone=UTC&forceConnectionTimeZoneToSession=true&preserveInstants=true",url);
        assertEquals(url,JdbcTimeConfig.utcUrl(url));
        HikariDataSource maria=new HikariDataSource();
        maria.setDriverClassName("org.mariadb.jdbc.Driver"); maria.setJdbcUrl(url);
        JdbcTimeConfig.utcDatabaseSessions().postProcessBeforeInitialization(maria,"dataSource");
        assertEquals(url,maria.getJdbcUrl()); maria.close();
        HikariDataSource h2=new HikariDataSource(); h2.setDriverClassName("org.h2.Driver"); h2.setJdbcUrl("jdbc:h2:mem:untouched");
        JdbcTimeConfig.utcDatabaseSessions().postProcessBeforeInitialization(h2,"dataSource");
        assertEquals("jdbc:h2:mem:untouched",h2.getJdbcUrl()); h2.close();
    }

    @Test void utcTimestampAndDateSerializationAreIndependentOfJvmZone() throws Exception {
        TimeZone original=TimeZone.getDefault();
        try {
            for(String zone:new String[]{"UTC","Asia/Shanghai","America/Los_Angeles"}) {
                TimeZone.setDefault(TimeZone.getTimeZone(zone));
                JdbcTemplate jdbc=new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:mem:utc_"+zone.replace('/','_')+";DB_CLOSE_DELAY=-1","sa",""));
                jdbc.execute("SET TIME ZONE 'UTC'");
                jdbc.execute("CREATE TABLE audit_logs(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, detail VARCHAR(30), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
                Db db=new Db(jdbc);
                Instant instant=Instant.parse("2026-10-20T16:56:00Z");
                long id=db.insert("audit_logs",Map.of("detail","utc","created_at",Timestamp.from(instant)));
                assertEquals(instant,((Timestamp)db.one("SELECT * FROM audit_logs WHERE id=?",id).get("CREATED_AT")).toInstant());
                ObjectMapper json=new ObjectMapper().registerModule(new JsonConfig().decimalStrings());
                assertEquals("\"2026-10-20T16:56:00Z\"",json.writeValueAsString(db.one("SELECT created_at FROM audit_logs WHERE id=?",id).get("CREATED_AT")));
                assertEquals("\"2026-10-20T16:56:00Z\"",json.writeValueAsString(LocalDateTime.of(2026,10,20,16,56)));
                assertEquals("\"2026-10-21\"",json.writeValueAsString(java.sql.Date.valueOf("2026-10-21")));
                assertTrue(db.insert("audit_logs",Map.of("detail","default timestamp"))>id,"Only id should be requested as a generated key");
            }
        } finally { TimeZone.setDefault(original); }
    }
}
